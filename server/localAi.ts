type LocalMessage = { role: "system" | "user" | "assistant"; content: string };

export type LocalAiMode = "chat" | "generate";

function latestUserMessage(messages: LocalMessage[]) {
  return [...messages].reverse().find(message => message.role === "user")?.content.trim() || "";
}

function includesAny(text: string, terms: string[]) {
  const normalised = text.toLocaleLowerCase();
  return terms.some(term => normalised.includes(term));
}

