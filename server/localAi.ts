export function isLocalAiEnabled() {
  return process.env.LOCAL_AI_ENABLED?.trim().toLowerCase() === "true";
}

export async function invokeLocalAi(
  options: { messages: LocalMessage[]; mode: LocalAiMode },
  onToken: (token: string) => Promise<void> | void,
) {
  const input = latestUserMessage(options.messages);
  const reply = localChatReply(input, options.messages);
  await onToken(reply);
}
