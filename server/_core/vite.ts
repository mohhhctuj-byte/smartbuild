import express, { type Express } from "express";
import fs from "fs";
import { type Server } from "http";
import { nanoid } from "nanoid";
import path from "path";
import { createServer as createViteServer } from "vite";
import viteConfig from "../../vite.config";

export async function setupVite(app: Express, server: Server, hmrClientPort: number) {
  const serverOptions = {
    middlewareMode: true,
    hmr: { server, clientPort: hmrClientPort },
    allowedHosts: true as const,
  };

  const vite = await createViteServer({
    ...viteConfig,
    configFile: false,
    server: serverOptions,
    appType: "custom",
  });

  app.use(vite.middlewares);
  app.use("*", async (req, res, next) => {
    const url = req.originalUrl;

    try {
      const clientTemplate = path.resolve(
        import.meta.dirname,
        "../..",
        "client",
        "index.html"
      );

      // always reload the index.html file from disk incase it changes
      let template = await fs.promises.readFile(clientTemplate, "utf-8");
      template = template.replace(
        `src="/src/main.tsx"`,
        `src="/src/main.tsx?v=${nanoid()}"`
      );
      const page = await vite.transformIndexHtml(url, template);
      res.status(200).set({ "Content-Type": "text/html" }).end(page);
    } catch (e) {
      vite.ssrFixStacktrace(e as Error);
      next(e);
    }
  });
}

export function serveStatic(app: Express) {
  const distPath = path.resolve(
    import.meta.dirname,
    process.env.NODE_ENV === "development" ? "../.." : ".",
    process.env.NODE_ENV === "development" ? "dist/public" : "public",
  );
  const clientPath = path.resolve(import.meta.dirname, "../..", "client");
  if (!fs.existsSync(distPath)) {
    console.error(
      `Could not find the build directory: ${distPath}, make sure to build the client first`
    );
  }

  app.use(express.static(distPath));

  // fall through to index.html if the file doesn't exist
  app.use("*", (_req, res, next) => {
    const indexPath = path.resolve(distPath, "index.html");
    if (fs.existsSync(indexPath)) {
      res.sendFile(indexPath);
      return;
    }
    // Keep a useful development fallback when the server is started without a client build.
    const clientIndexPath = path.resolve(clientPath, "index.html");
    if (process.env.NODE_ENV === "development" && fs.existsSync(clientIndexPath)) {
      res.sendFile(clientIndexPath);
      return;
    }
    next(new Error(`Could not find the frontend entrypoint: ${indexPath}`));
  });
}
